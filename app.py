def defaults():
    return [{"code":f"{b.replace('&','')}-S{s}-{i}","branch":b,"semester":s,"name":f"Subject {i}","lecturer_name":"Not assigned","profession":"Faculty","active":True}
      for b in BRANCHES for s in SEMESTERS for i in range(1,6)]

def db():
    if not DATABASE_URL: raise RuntimeError("DATABASE_URL is not configured.")
    import psycopg
    return psycopg.connect(DATABASE_URL,connect_timeout=10,sslmode="require")

def ensure_db():
    if not DATABASE_URL:return
    with db() as conn:
      with conn.cursor() as cur:
        cur.execute("""CREATE TABLE IF NOT EXISTS course_feedback_submissions(
        feedback_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,course_code VARCHAR(40) NOT NULL,
        course_name VARCHAR(180) NOT NULL,ratings SMALLINT[] NOT NULL,comment_optional VARCHAR(500) NOT NULL DEFAULT '',
        submitted_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),student_name VARCHAR(120) NOT NULL DEFAULT '',
        student_id VARCHAR(60) NOT NULL DEFAULT '',branch VARCHAR(30) NOT NULL DEFAULT '',semester SMALLINT NOT NULL DEFAULT 1,
        lecturer_name VARCHAR(120) NOT NULL DEFAULT '',faculty_profession VARCHAR(100) NOT NULL DEFAULT '')""")
        for col,typ in [("student_name","VARCHAR(120) NOT NULL DEFAULT ''"),("student_id","VARCHAR(60) NOT NULL DEFAULT ''"),
          ("branch","VARCHAR(30) NOT NULL DEFAULT ''"),("semester","SMALLINT NOT NULL DEFAULT 1"),
          ("lecturer_name","VARCHAR(120) NOT NULL DEFAULT ''"),("faculty_profession","VARCHAR(100) NOT NULL DEFAULT ''")]:
          cur.execute(f"ALTER TABLE course_feedback_submissions ADD COLUMN IF NOT EXISTS {col} {typ}")
        cur.execute("""CREATE TABLE IF NOT EXISTS edupulse_courses(course_code VARCHAR(40) PRIMARY KEY,branch VARCHAR(30) NOT NULL,
        semester SMALLINT NOT NULL,subject_name VARCHAR(180) NOT NULL,lecturer_name VARCHAR(120) NOT NULL DEFAULT 'Not assigned',
        faculty_profession VARCHAR(100) NOT NULL DEFAULT 'Faculty',active BOOLEAN NOT NULL DEFAULT TRUE)""")
      conn.commit()

def load_catalog():
    if DATABASE_URL:
      ensure_db()
      with db() as conn:
       with conn.cursor() as cur:
        cur.execute("SELECT course_code,branch,semester,subject_name,lecturer_name,faculty_profession,active FROM edupulse_courses")
        rows=cur.fetchall()
        if not rows:
          for c in defaults():
            cur.execute("INSERT INTO edupulse_courses VALUES(%s,%s,%s,%s,%s,%s,%s) ON CONFLICT DO NOTHING",
              (c["code"],c["branch"],c["semester"],c["name"],c["lecturer_name"],c["profession"],c["active"]))
          conn.commit()
          cur.execute("SELECT course_code,branch,semester,subject_name,lecturer_name,faculty_profession,active FROM edupulse_courses")
          rows=cur.fetchall()
      return [dict(code=r[0],branch=r[1],semester=r[2],name=r[3],lecturer_name=r[4],profession=r[5],active=r[6]) for r in rows]
    if not CATALOG_FILE.exists():
      DATA_DIR.mkdir(parents=True,exist_ok=True); CATALOG_FILE.write_text(json.dumps(defaults(),indent=2),encoding="utf-8")
    try:return json.loads(CATALOG_FILE.read_text(encoding="utf-8"))
    except Exception:return defaults()

def save_catalog(courses):
    if DATABASE_URL:
      ensure_db()
      with db() as conn:
       with conn.cursor() as cur:
        for c in courses:
         cur.execute("""INSERT INTO edupulse_courses VALUES(%s,%s,%s,%s,%s,%s,%s) ON CONFLICT(course_code) DO UPDATE SET
         branch=EXCLUDED.branch,semester=EXCLUDED.semester,subject_name=EXCLUDED.subject_name,lecturer_name=EXCLUDED.lecturer_name,
         faculty_profession=EXCLUDED.faculty_profession,active=EXCLUDED.active""",
         (c["code"],c["branch"],c["semester"],c["name"],c["lecturer_name"],c["profession"],c["active"]))
       conn.commit()
    else:
      DATA_DIR.mkdir(parents=True,exist_ok=True); CATALOG_FILE.write_text(json.dumps(courses,indent=2),encoding="utf-8")

def load_feedback():
    if DATABASE_URL:
      ensure_db()
      with db() as conn:
       with conn.cursor() as cur:
        cur.execute("""SELECT feedback_id,course_code,course_name,ratings,comment_optional,submitted_at,student_name,student_id,
        branch,semester,lecturer_name,faculty_profession FROM course_feedback_submissions ORDER BY feedback_id DESC""")
        rows=cur.fetchall()
      return [dict(feedback_id=r[0],course_code=r[1],course_name=r[2],ratings=list(r[3]),comment=r[4] or "",
        submitted_at=r[5].isoformat() if r[5] else "",student_name=r[6],student_id=r[7],branch=r[8],semester=r[9],
        lecturer_name=r[10],profession=r[11]) for r in rows]
    if ON_VERCEL:raise RuntimeError("Persistent database is not configured. Set DATABASE_URL.")
    if not DATA_FILE.exists():return []
    try:return json.loads(DATA_FILE.read_text(encoding="utf-8"))
    except Exception:return []

def insert_feedback(course,p,ratings,comment):
    row={"course_code":course["code"],"course_name":course["name"],"ratings":ratings,"comment":comment,
      "submitted_at":datetime.now(timezone.utc).isoformat(timespec="seconds"),"student_name":p["student_name"],
      "student_id":p["student_id"],"branch":course["branch"],"semester":course["semester"],
      "lecturer_name":course["lecturer_name"],"profession":course["profession"]}
    if DATABASE_URL:
      ensure_db()
      with db() as conn:
       with conn.cursor() as cur:
        cur.execute("""INSERT INTO course_feedback_submissions(course_code,course_name,ratings,comment_optional,submitted_at,
        student_name,student_id,branch,semester,lecturer_name,faculty_profession) VALUES(%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s)
        RETURNING feedback_id""",(row["course_code"],row["course_name"],ratings,comment,row["submitted_at"],row["student_name"],
        row["student_id"],row["branch"],row["semester"],row["lecturer_name"],row["profession"]))
        row["feedback_id"]=cur.fetchone()[0]
       conn.commit()
    else:
      DATA_DIR.mkdir(parents=True,exist_ok=True); rows=load_feedback()
      row["feedback_id"]=max([int(x.get("feedback_id") or 0) for x in rows],default=0)+1
      rows.append(row); DATA_FILE.write_text(json.dumps(rows,indent=2),encoding="utf-8")
    return row

def admin_required(fn):
 @wraps(fn)
 def inner(*a,**kw):
  if not session.get("is_admin"):
   if request.path.startswith("/admin/api/"):return jsonify({"error":"Admin sign-in required."}),401
   return redirect(url_for("admin_login"))
  return fn(*a,**kw)
 return inner

def summarize(rows,courses):
    stats=[]
    for c in courses:
      items=[r for r in rows if r.get("course_code")==c["code"]]; vals=[int(x) for r in items for x in r.get("ratings",[])]
      q=[]
      for i in range(5):
       v=[int(r["ratings"][i]) for r in items if len(r.get("ratings",[]))>i]; q.append(round(sum(v)/len(v),2) if v else 0)
      stats.append(dict(code=c["code"],name=c["name"],branch=c["branch"],semester=c["semester"],responses=len(items),
        average=round(sum(vals)/len(vals),2) if vals else 0,question_averages=q,suppressed=False))
    vals=[int(x) for r in rows for x in r.get("ratings",[])]; dist={str(i):vals.count(i) for i in range(1,6)}
    return dict(total_responses=len(rows),total_ratings=len(vals),overall_average=round(sum(vals)/len(vals),2) if vals else 0,
      distribution=dist,courses=stats,questions=QUESTIONS,course_count=len(courses))

